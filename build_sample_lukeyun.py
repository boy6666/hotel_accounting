# 假预订人/手机号（对应订单顺序；SC-05 红线：这些绝不出现在任何解析/上传结果）
FAKE_GUEST = [
    ("张三", "13900001111"), ("李四", "13700002222"), ("王五", "13600003333"),
    ("赵六", "13500004444"), ("钱七", "15800005555"), ("孙八", "18800006666"),
    ("周九", "18900007777"), ("吴十", "13300008888"),
]

def build():
    wb = Workbook()
    wb.active.title = "当月成本"
    ws1 = wb.active
    ws1.cell(1, 1, "当月成本明细（2023年7月）")
    ws1.cell(2, 1, "说明：每笔只填金额；“类型”下拉选 固定 / 变动 / 一次性（回本测算用）；当月没花的项留空。新项目直接往下面空行里加。")
    for c, h in enumerate(["序号", "费用项目", "金额（元）", "类型", "备注"], start=1):
        ws1.cell(4, c, h)
    for i, (no, name, amt, typ, note) in enumerate(COSTS, start=1):
        r = 4 + i
        ws1.cell(r, 1, no)
        ws1.cell(r, 2, name)
        ws1.cell(r, 3, amt)
        ws1.cell(r, 4, typ)
        if note:
            ws1.cell(r, 5, note)

    ws2 = wb.create_sheet("当月销售利润")
    ws2.cell(1, 1, "当月销售利润（路客云订单导出直用）")
    ws2.cell(2, 1, "说明：整表粘贴路客云后台导出的订单明细，表头不变。")
    for c, h in enumerate(LK_HEADER, start=1):
        ws2.cell(4, c, h)
    for i, o in enumerate(ORDERS, start=5):
        chan, han, cm, jie, other, room, ckin, nights, people, status, assigned, counted = o
        guest_name, guest_phone = FAKE_GUEST[i - 5]
        dep = (datetime.strptime(ckin, "%Y-%m-%d") + timedelta(days=nights)).strftime("%Y-%m-%d")
        vals = {
            1: han, 2: cm, 3: jie, 4: other,
            5: round(han + other, 2), 6: round(jie + other, 2),
            10: f"LKY-S{i:02d}", 11: f"PT-{i:02d}", 12: chan,
            13: guest_name, 14: guest_phone, 15: "露台海景loft亲子房",
            17: room, 18: ckin, 19: dep, 20: nights, 21: people, 22: status,
            24: f"2023-0{i:02d}-01", 28: "是" if assigned == "是" else "否",
            29: assigned, 30: counted,
        }
        for col, v in vals.items():
            ws2.cell(i, col, v)

    wb.save(OUT)
    print("saved:", OUT)
    print("sheets:", wb.sheetnames)

if __name__ == "__main__":
    build()
